_CATALOGS = {"en": EN, "fa": FA}
_LANGUAGES = {
    "en": ("English", "ltr"),
    "fa": ("فارسی", "rtl"),
}

_current = "en"


def available_languages() -> Dict[str, str]:
    return {code: meta[0] for code, meta in _LANGUAGES.items()}


def is_rtl(lang: str | None = None) -> bool:
    return _LANGUAGES.get(lang or _current, ("", "ltr"))[1] == "rtl"


def set_language(code: str) -> None:
    global _current
    if code in _CATALOGS:
        _current = code


def get_language() -> str:
    return _current


def detect_system_language() -> str:
    try:
        code = (locale.getdefaultlocale()[0] or "en").lower()
    except Exception:
        code = "en"
    if code.startswith("fa") or code.startswith("ir"):
        return "fa"
    return "en"


def tr(key: str, **kwargs) -> str:
    """Translate `key`; fall back to English, then to the key itself."""
    catalog = _CATALOGS.get(_current, EN)
    text = catalog.get(key) or EN.get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def keys_missing_in(lang: str) -> list[str]:
    catalog = _CATALOGS.get(lang, {})
    return sorted(k for k in EN if k not in catalog)
